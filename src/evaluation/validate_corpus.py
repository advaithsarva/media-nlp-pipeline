"""Runs the detectors over real published text and reports what fired.

This answers the question the hand-written gold set cannot: **how often do these detectors
fire on prose that nobody wrote to trip them?**

The neutral corpus is Wikipedia. Encyclopaedic register, neutral-point-of-view policy,
written by people who had never heard of this project. It includes politics, war and
disaster pages on purpose, because those carry charged vocabulary while still being
neutrally written -- the hardest free precision test available. **Every finding on that
corpus is a candidate false positive**, and the report prints all of them with surrounding
context so each can be judged by hand.

The rhetorical corpus is public-domain political speeches. Unlabelled, so nothing here is
a recall figure. It exists to answer a different question: are the detectors simply inert
on real persuasive writing? A detector that never fires has perfect precision and no value.

    python -m evaluation.validate_corpus --corpus eval/corpus --report eval/validation.md

The headline number is **findings per 1,000 words**, because raw counts are meaningless
across documents of different lengths.
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from main import PipelineRunner        # noqa: E402

CONTEXT = 60      # characters either side of a finding, for the by-hand inspection list


def run_group(runner, folder, documents):
    """Process one corpus group and collect every finding with its context."""
    findings = []
    total_words = 0
    total_docs = 0
    per_document = []

    for entry in documents:
        path = folder / Path(entry["file"]).name
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        if not text.strip():
            continue

        record = runner.process_document({"text": text, "source_type": "api_rest"})
        words = record["stats"]["word_count"]
        total_words += words
        total_docs += 1

        for finding in record["findings"]:
            start, end = finding["start_char"], finding["end_char"]
            # the invariant, re-checked on somebody else's text rather than on ours
            assert text[start:end] == finding["text"], (entry["title"], finding)
            findings.append({
                "document": entry["title"],
                "category": finding["category"],
                "rule_id": finding["rule_id"],
                "text": finding["text"],
                "context": text[max(0, start - CONTEXT):end + CONTEXT].replace("\n", " "),
            })

        per_document.append({
            "title": entry["title"],
            "words": words,
            "findings": len(record["findings"]),
            "categories": sorted({f["category"] for f in record["findings"]}),
        })

    return {
        "documents": total_docs,
        "words": total_words,
        "findings": findings,
        "per_document": per_document,
        "per_1k_words": round(len(findings) / total_words * 1000, 4) if total_words else 0.0,
    }


def summarise_by_category(group, taxonomy_ids):
    counts = defaultdict(int)
    for finding in group["findings"]:
        counts[finding["category"]] += 1
    words = group["words"] or 1
    return {
        category: {
            "count": counts[category],
            "per_1k_words": round(counts[category] / words * 1000, 4),
        }
        for category in taxonomy_ids
    }


def to_markdown(results, taxonomy_ids):
    neutral, rhetorical = results["neutral"], results["rhetorical"]
    n_by_cat = results["neutral_by_category"]
    r_by_cat = results["rhetorical_by_category"]

    lines = []
    lines.append("# Validation against real published text")
    lines.append("")
    lines.append("Generated by `python -m evaluation.validate_corpus`. The corpus is fetched")
    lines.append("live by `evaluation.fetch_corpus` and is not committed to this repository.")
    lines.append("")
    lines.append("| Corpus | Source | Documents | Words | Findings | Per 1,000 words |")
    lines.append("|---|---|---|---|---|---|")
    lines.append("| neutral | Wikipedia (CC BY-SA 4.0) | " + str(neutral["documents"]) + " | "
                 + format(neutral["words"], ",") + " | " + str(len(neutral["findings"]))
                 + " | **" + str(neutral["per_1k_words"]) + "** |")
    lines.append("| rhetorical | Wikisource (public domain) | " + str(rhetorical["documents"])
                 + " | " + format(rhetorical["words"], ",") + " | "
                 + str(len(rhetorical["findings"])) + " | **"
                 + str(rhetorical["per_1k_words"]) + "** |")
    lines.append("")

    if neutral["per_1k_words"] > 0:
        ratio = rhetorical["per_1k_words"] / neutral["per_1k_words"]
        lines.append("Rhetorical text fires **" + ("%.1f" % ratio) + "x** more often per word "
                     "than encyclopaedic text.")
    else:
        lines.append("Nothing fired on the neutral corpus at all.")
    lines.append("")
    lines.append("Every neutral finding is a **candidate false positive** and is listed in full")
    lines.append("below with context, so each can be judged rather than assumed. Wikipedia is")
    lines.append("written to a neutral-point-of-view policy, but it is not a labelled dataset:")
    lines.append("a page can still quote someone else's charged language, and quoting is not")
    lines.append("something this pipeline can currently tell apart from asserting.")
    lines.append("")

    lines.append("## Per detector")
    lines.append("")
    lines.append("| Detector | Neutral count | Neutral /1k | Rhetorical count | Rhetorical /1k |")
    lines.append("|---|---|---|---|---|")
    for category in sorted(taxonomy_ids):
        n, r = n_by_cat[category], r_by_cat[category]
        if n["count"] == 0 and r["count"] == 0:
            continue
        lines.append("| `" + category + "` | " + str(n["count"]) + " | " + str(n["per_1k_words"])
                     + " | " + str(r["count"]) + " | " + str(r["per_1k_words"]) + " |")
    lines.append("")
    silent = [c for c in sorted(taxonomy_ids)
              if n_by_cat[c]["count"] == 0 and r_by_cat[c]["count"] == 0]
    if silent:
        lines.append("Silent on both corpora: " + ", ".join("`" + c + "`" for c in silent))
        lines.append("")
        lines.append("Silence is not automatically good. A detector that never fires on any real")
        lines.append("text has perfect precision and no value, and the two cannot be told apart")
        lines.append("without text that genuinely contains the thing it looks for.")
        lines.append("")

    lines.append("## Every neutral finding, for inspection")
    lines.append("")
    if not neutral["findings"]:
        lines.append("None.")
    else:
        by_category = defaultdict(list)
        for finding in neutral["findings"]:
            by_category[finding["category"]].append(finding)
        for category in sorted(by_category):
            items = by_category[category]
            lines.append("### `" + category + "` -- " + str(len(items)))
            lines.append("")
            for finding in items:
                lines.append("- **" + finding["document"] + "** | matched `"
                             + finding["text"] + "`")
                lines.append("  > ..." + finding["context"].strip() + "...")
            lines.append("")

    lines.append("## Documents with the most findings")
    lines.append("")
    lines.append("| Document | Corpus | Words | Findings | Categories |")
    lines.append("|---|---|---|---|---|")
    rows = ([(d, "neutral") for d in neutral["per_document"]]
            + [(d, "rhetorical") for d in rhetorical["per_document"]])
    rows.sort(key=lambda r: -r[0]["findings"])
    for document, corpus in rows[:15]:
        lines.append("| " + document["title"] + " | " + corpus + " | "
                     + format(document["words"], ",") + " | " + str(document["findings"])
                     + " | " + (", ".join(document["categories"]) or "-") + " |")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Validate detectors against real text.")
    parser.add_argument("--corpus", default="eval/corpus")
    parser.add_argument("--report", help="write the markdown report here")
    parser.add_argument("--json", help="write the raw results here")
    parser.add_argument("--conf")
    parser.add_argument("--max-neutral-rate", type=float,
                        help="exit non-zero if neutral findings per 1,000 words exceeds this")
    args = parser.parse_args(argv)

    corpus = Path(args.corpus)
    manifest = json.loads((corpus / "manifest.json").read_text(encoding="utf-8"))
    runner = PipelineRunner(args.conf) if args.conf else PipelineRunner()
    taxonomy_ids = runner.taxonomy.ids()

    neutral = run_group(runner, corpus / "neutral", manifest["neutral"]["documents"])
    rhetorical = run_group(runner, corpus / "rhetorical", manifest["rhetorical"]["documents"])

    results = {
        "neutral": neutral,
        "rhetorical": rhetorical,
        "neutral_by_category": summarise_by_category(neutral, taxonomy_ids),
        "rhetorical_by_category": summarise_by_category(rhetorical, taxonomy_ids),
    }

    report = to_markdown(results, taxonomy_ids)
    # The corpus is real text and contains Greek, accents and dashes. The Windows console
    # is cp1252 by default and raises on those, so reconfigure rather than lose the report.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except AttributeError:
        pass
    print(report)

    if args.report:
        Path(args.report).parent.mkdir(parents=True, exist_ok=True)
        Path(args.report).write_text(report + "\n", encoding="utf-8")
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2, sort_keys=True) + "\n",
                                   encoding="utf-8")

    if args.max_neutral_rate is not None and neutral["per_1k_words"] > args.max_neutral_rate:
        print("\nFAIL: neutral firing rate " + str(neutral["per_1k_words"])
              + " exceeds " + str(args.max_neutral_rate))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
